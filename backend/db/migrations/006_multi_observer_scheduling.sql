-- Fix #6 (professor feedback, 10/13): flip the scheduling model from "one
-- observer confirms one of the observee's dates" to "the observee receives
-- proposals back from several different observers and picks one date from
-- whichever observer worked out" -- e.g. 3 candidates x 4 times each, and
-- the observee chooses, constrained so the chosen slot doesn't double-book
-- their own schedule (checked in the API via src/lib/availability.js, same
-- helper used for fix #4).
--
-- This supersedes assessment_time_options.offered_to_teacher_id as "the one
-- observer this whole batch went to" (migration 004's documented 9/30
-- design) -- that column assumed exactly one observer could ever be offered
-- a given option row. Under this fix, several observers can each be offered,
-- and can each accept or decline, the same date/time; a new junction table
-- records that per (option, teacher) instead of overloading one column on
-- assessment_time_options.
--
-- offered_to_teacher_id itself is left in place (not dropped) for backward
-- compatibility with any already-sent single-observer batches from before
-- this migration; new sends use time_option_offers instead. The API no
-- longer writes to offered_to_teacher_id.

CREATE TABLE time_option_offers (
  id          INT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  option_id   INT  NOT NULL REFERENCES assessment_time_options (id) ON DELETE CASCADE,
  teacher_id  INT  NOT NULL REFERENCES teachers (id) ON DELETE CASCADE,
  -- 'pending' (sent, no response yet), 'accepted' (observer is willing --
  -- this is NOT final, the observee still has to pick one), 'declined'.
  status      TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (option_id, teacher_id)
);

CREATE INDEX time_option_offers_option_idx  ON time_option_offers (option_id);
CREATE INDEX time_option_offers_teacher_idx ON time_option_offers (teacher_id, status);

CREATE TRIGGER time_option_offers_set_updated_at
  BEFORE UPDATE ON time_option_offers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Which observer's accepted offer the observee actually finalized -- needed
-- now that more than one teacher may have accepted the same date/time.
ALTER TABLE assessment_time_options
  ADD COLUMN confirmed_teacher_id INT REFERENCES teachers (id) ON DELETE SET NULL;
