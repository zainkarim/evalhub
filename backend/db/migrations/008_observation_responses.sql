-- #21/#22: observation_responses -- "Stores the observer's multiple-choice
-- ranking answers per criterion, tied to one observation."
--
-- DESIGN (#21):
--   - One row per (observation_id, criterion_id): the observer answers each
--     active evaluation_criteria question exactly once per observation.
--     UNIQUE(observation_id, criterion_id) enforces that directly, so a
--     resubmit has to be an UPDATE, not a second row -- matching #23's
--     "observer submits answers (cannot edit questions)": the *questions*
--     are fixed, but nothing here prevents amending an answer before sign-
--     off, which is what #23's submit endpoint uses (upsert, not insert-only).
--   - score is the multiple-choice "ranking" answer itself, an integer
--     against criterion.max_score (evaluation_criteria.max_score, default
--     5 -- i.e. a 1-5 ranking unless the AC configured a different scale
--     for that question). A plain CHECK can't reference another table's
--     column, so the 1..max_score range is enforced by the trigger below
--     instead of a CHECK -- same reasoning migration 002 gives for why
--     human-in-the-loop rules live in triggers/constraints and not just
--     the API ("enforced by the database, not just the API").
--   - criterion_id uses ON DELETE RESTRICT (same choice migration 002 made
--     for observations.observer_id): once an observer has actually
--     answered a question, that question can't be deleted out from under
--     the answer. criteria.js's DELETE route surfaces this as a normal 409
--     via the existing 23503 -> 409 error-handler mapping -- retiring a
--     used question is PATCH isActive:false instead, not DELETE.
--   - No separate "submitted_at" column: the table's existence for a given
--     (observation, criterion) pair *is* "submitted" for that question, and
--     #23's read-gating ("view once submitted and signed") is driven by
--     observations.observer_signed_off_at instead -- sign-off, not row
--     presence, is what "submitted" needs to mean for the observee's view
--     (an observer could otherwise leave answers half-filled and have the
--     observee see a partial, misleading result).

CREATE TABLE observation_responses (
  id             INT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  observation_id INT      NOT NULL REFERENCES observations (id) ON DELETE CASCADE,
  criterion_id   INT      NOT NULL REFERENCES evaluation_criteria (id) ON DELETE RESTRICT,
  score          SMALLINT NOT NULL CHECK (score > 0),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (observation_id, criterion_id)
);
CREATE INDEX observation_responses_observation_idx ON observation_responses (observation_id);

CREATE TRIGGER observation_responses_set_updated_at
  BEFORE UPDATE ON observation_responses
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE FUNCTION enforce_response_score_range() RETURNS trigger AS $$
DECLARE
  max SMALLINT;
BEGIN
  SELECT max_score INTO max FROM evaluation_criteria WHERE id = NEW.criterion_id;
  IF max IS NULL THEN
    RAISE EXCEPTION 'criterion % does not exist', NEW.criterion_id;
  END IF;
  IF NEW.score > max THEN
    RAISE EXCEPTION 'score % exceeds criterion %''s max_score of %', NEW.score, NEW.criterion_id, max;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER observation_responses_score_range
  BEFORE INSERT OR UPDATE ON observation_responses
  FOR EACH ROW EXECUTE FUNCTION enforce_response_score_range();
