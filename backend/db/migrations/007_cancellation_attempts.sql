-- #11/#12: cancellation behavior change (9/30 meeting: never delete/cancel a
-- sign-up). Previously POST /assessments/:id/cancel set assessments.status
-- to 'cancelled', which is the exact thing the 9/30 decision ruled out. The
-- new behavior (see assessments.js) leaves the assessment active and moves
-- it to 'postponed' instead, and logs the cancellation *attempt* itself --
-- who asked, when, and why -- so that history isn't lost just because the
-- request wasn't honored as a real cancellation.
--
-- A log TABLE (rather than cancel_requested_at/cancel_requested_reason
-- columns directly on assessments, the other option #12 named) because an
-- assessment can reasonably have more than one cancellation attempt over
-- its lifetime (denied once, asked again later) and a single pair of
-- columns can only ever hold the most recent one -- losing exactly the
-- audit trail this feature exists to keep.
CREATE TABLE cancellation_attempts (
  id             INT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id  INT  NOT NULL REFERENCES assessments (id) ON DELETE CASCADE,
  requested_by   INT  REFERENCES users (id) ON DELETE SET NULL, -- who asked (AC/admin today; see assessments.js note on who's allowed)
  reason         TEXT NOT NULL CHECK (reason IN ('not_eligible', 'left_department', 'other')),
  notes          TEXT,
  requested_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX cancellation_attempts_assessment_idx ON cancellation_attempts (assessment_id);
